CREATE TABLE IF NOT EXISTS `kg_exam_outbox` (
  `id` int(11) unsigned NOT NULL AUTO_INCREMENT,
  `event_id` varchar(64) NOT NULL DEFAULT '' COMMENT '事件编号 evt_ 前缀',
  `event_type` varchar(64) NOT NULL DEFAULT '' COMMENT 'learning.progress.updated / course.completed',
  `event_version` varchar(10) NOT NULL DEFAULT '1.0',
  `user_id` int(11) unsigned NOT NULL DEFAULT '0' COMMENT '内部用户编号',
  `course_id` int(11) unsigned NOT NULL DEFAULT '0',
  `user_key` varchar(64) NOT NULL DEFAULT '' COMMENT '对外 userId（OIDC sub）',
  `course_key` varchar(64) NOT NULL DEFAULT '' COMMENT '对外 courseId',
  `progress` int(11) unsigned NOT NULL DEFAULT '0' COMMENT '入箱时进度，用于节流比较',
  `payload` text COMMENT '事件封套 JSON',
  `status` tinyint(3) unsigned NOT NULL DEFAULT '0' COMMENT '0待发 1已发 2待重试 3死信',
  `retry_count` int(11) unsigned NOT NULL DEFAULT '0',
  `next_retry_at` int(11) unsigned NOT NULL DEFAULT '0',
  `last_error` varchar(500) NOT NULL DEFAULT '',
  `response_code` int(11) NOT NULL DEFAULT '0' COMMENT '网关返回状态码，0 为网络层失败',
  `request_id` varchar(64) NOT NULL DEFAULT '',
  `occurred_at` int(11) unsigned NOT NULL DEFAULT '0',
  `sent_at` int(11) unsigned NOT NULL DEFAULT '0',
  `dead_at` int(11) unsigned NOT NULL DEFAULT '0',
  `create_time` int(11) unsigned NOT NULL DEFAULT '0',
  `update_time` int(11) unsigned NOT NULL DEFAULT '0',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uniq_event_id` (`event_id`),
  KEY `idx_due` (`status`,`next_retry_at`),
  KEY `idx_user_course` (`user_id`,`course_id`),
  KEY `idx_type` (`event_type`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='学习进度推送发件箱（考试平台）';
