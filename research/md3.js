const { chromium } = require('playwright');
const OUT = 'C:/Users/paradox/Desktop/自学·平台/research/shots';
(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 2, locale: 'zh-CN' });
  const page = await ctx.newPage();
  await page.goto('https://school.moodledemo.net/login/index.php', { waitUntil: 'domcontentloaded' });
  await page.waitForTimeout(2000);
  await page.fill('#username', 'student');
  await page.fill('#password', 'moodle26');
  await page.click('#loginbtn');
  await page.waitForTimeout(5000);
  console.log('after login:', page.url());
  console.log('TEXT:', (await page.evaluate(() => document.body.innerText.replace(/\n+/g,' | '))).slice(0, 300));
  await page.goto('https://school.moodledemo.net/my/courses.php', { waitUntil: 'domcontentloaded' });
  await page.waitForTimeout(3500);
  await page.screenshot({ path: OUT + '/md_01_mycourses.png' });
  console.log('MY:', (await page.evaluate(() => document.body.innerText.replace(/\n+/g,' | '))).slice(0, 600));
  const links = await page.$$eval('a', els => [...new Set(els.map(e => e.getAttribute('href')||'').filter(h => /course\/view\.php\?id=\d+/.test(h)))]);
  console.log('COURSE LINKS:', JSON.stringify(links.slice(0,5)));
  await browser.close();
})();
